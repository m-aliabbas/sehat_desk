def module_of(action: str) -> str:
    return MODULES.get(action.split(".", 1)[0], action.split(".", 1)[0].replace("_", " ").title())


def label(action: str) -> str:
    if action in LABELS:
        return LABELS[action]
    return action.replace("_", " ").replace(".", " · ").capitalize()
